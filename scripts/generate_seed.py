def parse_players(s):
    s = s.strip().replace('인', '')
    if '-' in s:
        parts = s.split('-')
        return int(parts[0]), int(parts[1])
    return int(s), int(s)

def parse_duration(s):
    s = s.strip().replace('분', '').replace(' ', '')
    if '-' in s:
        parts = s.split('-')
        return int(parts[0]), int(parts[1])
    return int(s), int(s)

